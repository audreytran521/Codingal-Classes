import math 
print('the floor and ceiling of 43.23 are: ' + str(math.ceil(43.23)) + ', ' + str(math.floor(43.23)))
x = 32
y = -12
# x takes the sign in front of the y value
print("the value of x after copying the sign from the y is: " + str(math.copysign(x, y)))
print(' absolute value of -23 and 32 are: ' + str(math.fabs(-23)) + ', ' + str(math.fabs(32)))
print('The GCD of 24 and 36 : ' + str(math.gcd(24, 36)))
